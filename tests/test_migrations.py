"""迁移与模型是否同步：`alembic check` 的 pytest 版。

M2-2 让测试库由迁移建表，解决的是「迁移能不能跑通」。
这个文件解决另一半：「迁移和 models.py 有没有跑偏」。

场景：你改了 models.py（加一列），却忘了 `alembic revision --autogenerate`。
开发库是老结构、测试库也是老结构 —— 所有测试全绿，问题被完美掩盖。
`alembic check` 会把「模型有、迁移没有」的差异揪出来，这条测试就红。
"""

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

from conftest import PROJECT_ROOT, TEST_URL

pytestmark = pytest.mark.integration


def _alembic_config() -> Config:
    """跟 conftest.prepare_database 用同一套配置，只是不执行迁移"""
    cfg = Config(str(PROJECT_ROOT / "alembic.ini"))
    cfg.set_main_option("script_location", str(PROJECT_ROOT / "alembic"))
    cfg.attributes["db_url"] = TEST_URL
    return cfg


def test_migrations_match_models():
    """模型和迁移必须一致；不一致就说明有人改了模型没生成迁移"""
    try:
        command.check(_alembic_config())
    except AutogenerateDiffsDetected as e:
        pytest.fail(
            "models.py 与迁移脚本不一致，请执行：\n"
            "  alembic revision --autogenerate -m \"描述\"\n"
            f"差异详情：\n{e}"
        )
